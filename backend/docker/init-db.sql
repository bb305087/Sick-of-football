DO $$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'sof_migrator') THEN
    CREATE ROLE sof_migrator LOGIN PASSWORD 'change-me' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'sof_app') THEN
    CREATE ROLE sof_app LOGIN PASSWORD 'change-me' NOSUPERUSER NOCREATEDB NOCREATEROLE;
  END IF;
END $$;
GRANT CONNECT ON DATABASE sof TO sof_migrator, sof_app;
GRANT USAGE ON SCHEMA public TO sof_migrator, sof_app;
GRANT CREATE ON SCHEMA public TO sof_migrator;
ALTER DEFAULT PRIVILEGES FOR ROLE sof_migrator IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO sof_app;
ALTER DEFAULT PRIVILEGES FOR ROLE sof_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO sof_app;
